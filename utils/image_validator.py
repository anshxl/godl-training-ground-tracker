"""
Image validation using Google Gemini VLM to verify aim training screenshots.
"""
import os
import json
import logging
from typing import Tuple
from google import genai
from google.genai import types
import requests
import tempfile

logger = logging.getLogger(__name__)

try:
    from c2pa import Reader
    C2PA_AVAILABLE = True
except ImportError:
    C2PA_AVAILABLE = False
    logger.warning("c2pa-python not installed, AI-generated image detection disabled")

def check_provenance(image_bytes: bytes, content_type: str = 'image/jpeg') -> str:
    """
    Check C2PA provenance metadata to detect AI-generated images.

    Args:
        image_bytes: Raw image bytes
        content_type: MIME type of the image (e.g., 'image/jpeg', 'image/png')

    Returns:
        "AI_GENERATED" if image is AI-generated, "UNKNOWN" otherwise
    """
    if not C2PA_AVAILABLE:
        return "UNKNOWN"

    tmp_path = None
    try:
        # Determine file extension from content type
        extension = '.jpg'
        if 'png' in content_type.lower():
            extension = '.png'
        elif 'jpeg' in content_type.lower() or 'jpg' in content_type.lower():
            extension = '.jpg'
        elif 'webp' in content_type.lower():
            extension = '.webp'

        # Write to temporary file for C2PA reader
        with tempfile.NamedTemporaryFile(delete=False, suffix=extension) as tmp_file:
            tmp_file.write(image_bytes)
            tmp_path = tmp_file.name

        # Read C2PA manifest
        with Reader(tmp_path) as reader:
            manifest_json_str = reader.json()
            manifest_data = json.loads(manifest_json_str)

            # Check multiple AI-generation indicators
            manifest_str_lower = manifest_json_str.lower()

            # 1. Check for Google/AI issuer in signature info
            for manifest in manifest_data.get("manifests", {}).values():
                sig_info = manifest.get("signature_info", {})
                issuer = sig_info.get("issuer", "").lower()
                if "google" in issuer:
                    logger.info(f"AI-generated image detected via C2PA (Google issuer: {sig_info.get('issuer')})")
                    return "AI_GENERATED"

                # 2. Check for AI-generation actions
                for assertion in manifest.get("assertions", []):
                    if assertion.get("label") == "c2pa.actions.v2":
                        actions = assertion.get("data", {}).get("actions", [])
                        for action in actions:
                            # Check for trainedAlgorithmicMedia digital source type
                            if "trainedalgorithmicmedia" in action.get("digitalSourceType", "").lower():
                                logger.info("AI-generated image detected via C2PA (trainedAlgorithmicMedia)")
                                return "AI_GENERATED"
                            # Check for AI-related descriptions
                            desc = action.get("description", "").lower()
                            if any(keyword in desc for keyword in ["generative ai", "synthid", "ai-generated"]):
                                logger.info(f"AI-generated image detected via C2PA (description: {action.get('description')})")
                                return "AI_GENERATED"

            # 3. Fallback: broad keyword check
            if any(keyword in manifest_str_lower for keyword in ["google generative", "synthid", "gemini"]):
                logger.info("AI-generated image detected via C2PA (keyword match)")
                return "AI_GENERATED"

    except Exception as e:
        logger.debug(f"C2PA check failed: {e}")

    finally:
        # Clean up temp file
        if tmp_path and os.path.exists(tmp_path):
            os.unlink(tmp_path)

    return "UNKNOWN"


VALIDATION_PROMPT = """You are validating aim training practice screenshots for a gaming team.

Analyze this image and determine if it is a VALID aim training/practice screenshot.

VALID screenshots must show:
1. **Game completion or results screen** with performance statistics
2. **Quantifiable metrics** on the top-right, such as:
   - Accuracy percentage
   - Kill count or target hits
   - Headshot accuracy
   - Damage dealt
   - Time to kill (TTK)
3. A big **"Mission Complete"** text in the center

INVALID screenshots include:
- Random gameplay screenshots without stats
- Memes, photos, or unrelated images
- Blank screens or loading screens
- Chat screenshots or lobby screens without practice stats
- Check for a SynthID watermark. If present, this indicates the image was generated by AI and should be marked INVALID.

Respond with EXACTLY ONE WORD:
- "VALID" if this is a legitimate aim training results screenshot
- "INVALID" if this does not meet the criteria

Your response:"""


async def validate_aim_screenshot(image_url: str) -> Tuple[bool, str]:
    """
    Validate if an image is a legitimate aim training screenshot.

    Args:
        image_url: Discord CDN URL or direct image URL

    Returns:
        Tuple of (is_valid: bool, reason: str)
    """
    try:
        # Initialize Gemini client
        client = genai.Client(api_key=os.environ.get("GEMINI_API_KEY"))

        # Download image
        logger.info(f"Downloading image from {image_url}")
        response = requests.get(image_url, timeout=10)
        response.raise_for_status()

        # Get image bytes and MIME type
        image_bytes = response.content
        content_type = response.headers.get('content-type', 'image/jpeg')

        # Check C2PA provenance for AI-generated images (fast, free check)
        provenance = check_provenance(image_bytes, content_type)
        if provenance == "AI_GENERATED":
            logger.warning("Rejected AI-generated image (detected via C2PA)")
            return False, "AI-generated images are not accepted"
        else:
            logger.info("No AI provenance detected via C2PA, proceeding with Gemini validation")
        # Generate validation response using Gemini 2.5 Flash Lite
        logger.info("Sending image to Gemini for validation...")
        result = client.models.generate_content(
            model="gemini-2.5-flash-lite",
            contents=[
                types.Part.from_bytes(
                    data=image_bytes,
                    mime_type=content_type,
                ),
                VALIDATION_PROMPT
            ],
        )

        response_text = result.text.strip().upper()
        logger.info(f"Gemini response: {response_text}")

        # Calculate and log cost
        if hasattr(result, 'usage_metadata'):
            input_tokens = result.usage_metadata.prompt_token_count
            output_tokens = result.usage_metadata.candidates_token_count
            total_tokens = result.usage_metadata.total_token_count

            # Gemini 2.5 Flash Lite pricing: $0.10/M input, $0.40/M output
            input_cost = (input_tokens / 1_000_000) * 0.10
            output_cost = (output_tokens / 1_000_000) * 0.40
            total_cost = input_cost + output_cost

            logger.info(
                f"Token usage - Input: {input_tokens}, Output: {output_tokens}, "
                f"Total: {total_tokens} | Cost: ${total_cost:.6f} "
                f"(${input_cost:.6f} + ${output_cost:.6f})"
            )

        # Parse response
        is_valid = "VALID" in response_text and "INVALID" not in response_text

        if is_valid:
            reason = "Screenshot validated as aim training practice"
        else:
            reason = "Image does not appear to be an aim training screenshot"

        return is_valid, reason

    except requests.exceptions.RequestException as e:
        logger.error(f"Failed to download image: {e}")
        return False, f"Failed to download image: {str(e)}"

    except Exception as e:
        logger.error(f"Image validation error: {e}")
        # IMPORTANT: Fail open - don't block users if validation service is down
        logger.warning("Validation service unavailable, accepting submission")
        return True, "Validation service unavailable (accepted by default)"


def is_image_attachment(attachment) -> bool:
    """Check if a Discord attachment is an image."""
    return attachment.content_type and attachment.content_type.startswith('image/')
